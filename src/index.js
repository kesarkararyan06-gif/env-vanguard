'use strict';

const { EnvValidationError, SchemaError } = require('./errors');
const { validateSpec, coerce } = require('./validate');

/**
 * @typedef {Object} FieldSpec
 * @property {'string'|'number'|'boolean'|'enum'} [type='string']
 *   The expected type. Defaults to `'string'`.
 * @property {boolean} [required=true]
 *   Whether the variable must be present. Defaults to `true`.
 * @property {string|number|boolean} [default]
 *   Default value used when the variable is absent (only valid when `required` is `false`).
 * @property {string[]} [values]
 *   Allowed values for type `'enum'`.
 * @property {string} [description]
 *   Human-readable description; used when generating `.env.example`.
 * @property {string} [example]
 *   Example value; used when generating `.env.example`.
 */

/**
 * @typedef {Object<string, FieldSpec>} Schema
 */

/**
 * @typedef {Object} ValidateOptions
 * @property {boolean} [strict=false]
 *   When `true`, any variable present in `env` but not in `schema` causes an error.
 * @property {Object<string,string>} [env=process.env]
 *   The environment object to validate (defaults to `process.env`).
 */

/**
 * Validates environment variables against a schema.
 *
 * Collects ALL validation errors before throwing so you see every
 * problem at once. Returns a frozen object of coerced values on success.
 *
 * @param {Schema} schema - The variable definitions.
 * @param {ValidateOptions} [options={}] - Optional configuration.
 * @returns {Object<string, string|number|boolean>} Frozen object of coerced values.
 * @throws {SchemaError} If the schema itself is malformed.
 * @throws {EnvValidationError} If one or more variables fail validation.
 *
 * @example
 * const env = validate({
 *   PORT:     { type: 'number', default: 3000, required: false },
 *   NODE_ENV: { type: 'enum', values: ['development', 'production', 'test'] },
 * });
 * console.log(env.PORT); // 3000 (number)
 */
function validate(schema, options = {}) {
  if (schema === null || typeof schema !== 'object' || Array.isArray(schema)) {
    throw new SchemaError('schema must be a plain object.');
  }

  const env = options.env ?? process.env;
  const strict = options.strict ?? false;
  const errors = [];
  const result = {};

  // Validate every spec definition first (fail-fast on bad schema)
  for (const [key, spec] of Object.entries(schema)) {
    validateSpec(key, spec); // throws SchemaError on invalid spec
  }

  // Check for extra variables in strict mode
  if (strict) {
    for (const key of Object.keys(env)) {
      if (!(key in schema)) {
        errors.push(`"${key}" is not declared in the schema (strict mode).`);
      }
    }
  }

  // Process each schema entry
  for (const [key, spec] of Object.entries(schema)) {
    const required = spec.required !== false; // default: required
    const raw = env[key];
    const isAbsent = raw === undefined || raw === null || raw === '';

    if (isAbsent) {
      if (spec.default !== undefined) {
        result[key] = spec.default;
      } else if (required) {
        errors.push(`"${key}" is required but was not provided.`);
      } else {
        // optional, no default → omit from result
      }
      continue;
    }

    const { value, error } = coerce(key, raw, spec);
    if (error) {
      errors.push(error);
    } else {
      result[key] = value;
    }
  }

  if (errors.length > 0) {
    throw new EnvValidationError(errors);
  }

  return Object.freeze(result);
}

/**
 * Generates a `.env.example` file content string from a schema.
 *
 * Each variable is printed with an optional comment block containing
 * its description and type information, followed by a sensible placeholder.
 *
 * @param {Schema} schema - The variable definitions.
 * @returns {string} The `.env.example` content.
 *
 * @example
 * const content = generateExample({
 *   PORT: { type: 'number', required: false, default: 3000, description: 'HTTP port' },
 * });
 * // # HTTP port
 * // # Type: number | Optional | Default: 3000
 * // PORT=3000
 */
function generateExample(schema) {
  if (schema === null || typeof schema !== 'object' || Array.isArray(schema)) {
    throw new SchemaError('schema must be a plain object.');
  }

  const lines = ['# .env.example — generated by env-vanguard', ''];

  for (const [key, spec] of Object.entries(schema)) {
    validateSpec(key, spec);

    const type = spec.type ?? 'string';
    const required = spec.required !== false;
    const comments = [];

    if (spec.description) {
      comments.push(`# ${spec.description}`);
    }

    const meta = [`Type: ${type}`];
    if (type === 'enum') {meta.push(`Allowed: ${spec.values.join(' | ')}`);}
    meta.push(required ? 'Required' : 'Optional');
    if (spec.default !== undefined) {meta.push(`Default: ${spec.default}`);}
    comments.push(`# ${meta.join(' | ')}`);

    lines.push(...comments);

    // Value: example > default > placeholder
    let val = '';
    if (spec.example !== undefined) {
      val = String(spec.example);
    } else if (spec.default !== undefined) {
      val = String(spec.default);
    } else if (type === 'enum') {
      val = spec.values[0];
    } else if (type === 'number') {
      val = '0';
    } else if (type === 'boolean') {
      val = 'false';
    }

    lines.push(`${key}=${val}`);
    lines.push('');
  }

  return lines.join('\n');
}

module.exports = { validate, generateExample, EnvValidationError, SchemaError };
